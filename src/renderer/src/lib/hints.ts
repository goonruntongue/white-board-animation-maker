/** 名前の形で決まる説明（番号付きのボタンなど） */
const PATTERNS: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^線 (\d+) を選ぶ$/, (m) => `グループの中の線 ${m[1]} を選び、その線が描かれる時間へ移ります`],
  [/^(\d+)秒$/, (m) => `このグループの再生時間を ${m[1]} 秒にします`]
]

/** ボタンの名前（とクラス名）から説明を探す。なければ undefined */
export function lookupHint(name: string, classes: string[]): string | undefined {
  const n = name.replace(/\s+/g, ' ').trim()
  // 数字のバッジが付いた名前（「1 描き順」など）は数字を除いても探す
  const bare = n.replace(/^\d+\s+/, '')
  for (const c of classes) {
    const v = HINTS[`${c}:${n}`] ?? HINTS[`${c}:${bare}`]
    if (v) return v
  }
  const v = HINTS[n] ?? HINTS[bare]
  if (v) return v
  for (const [re, fn] of PATTERNS) {
    const m = n.match(re)
    if (m) return fn(m)
  }
  return undefined
}
